#!/usr/bin/env python3
"""
generate_field.py

Writes a Gazebo world containing rows of tomato plants with pickable fruit.

Design notes
------------
Plants are anchored to the world with a fixed joint rather than marked
<static>, because a detachable joint needs a real (non-static) parent link.

Each fruit is its own model, held to its plant by a DetachableJoint. Sending
an empty message to the fruit's detach topic releases it, which is the
simulation equivalent of picking it. Until then the fruit stays put instead of
rolling off a branch, which is what would happen if it were merely resting on
one.

Row spacing defaults to 1.8 m: wide enough for a 0.75 m wide robot to drive
between rows with room for the arm to reach either side.

Usage
-----
    python3 generate_field.py --output ../worlds/tomato_field.sdf
    python3 generate_field.py --rows 4 --plants-per-row 8 --fruits 3
    python3 generate_field.py --rows 2 --plants-per-row 4 --fruits 1   # light
"""

import argparse
import math
import random

# ----------------------------------------------------------------------------
# geometry of a single plant (metres)
# ----------------------------------------------------------------------------
STEM_RADIUS = 0.025
STEM_HEIGHT = 0.90
FOLIAGE_RADIUS = 0.22
FOLIAGE_Z = 0.62          # centre height of the leafy mass
FRUIT_RADIUS = 0.035
FRUIT_MASS = 0.12

# heights at which fruit can hang, cycled through
FRUIT_HEIGHTS = [0.40, 0.55, 0.70, 0.30]


def header(world_name):
    return f'''<?xml version="1.0" ?>
<!--
  Generated by scripts/generate_field.py - do not edit by hand.
  Re-run the script to change the layout.
-->
<sdf version="1.9">
  <world name="{world_name}">

    <physics name="1ms" type="ignored">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>

    <plugin filename="gz-sim-physics-system"
            name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system"
            name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system"
            name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system"
            name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <plugin filename="gz-sim-imu-system"
            name="gz::sim::systems::Imu"/>
    <plugin filename="gz-sim-contact-system"
            name="gz::sim::systems::Contact"/>

    <scene>
      <ambient>0.6 0.6 0.6 1</ambient>
      <background>0.6 0.75 0.9 1</background>
      <sky/>
    </scene>

    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.95 0.92 0.85 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.4 0.3 -0.9</direction>
    </light>

    <model name="ground">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry>
            <plane><normal>0 0 1</normal><size>120 120</size></plane>
          </geometry>
          <surface>
            <friction><ode><mu>1.0</mu><mu2>1.0</mu2></ode></friction>
          </surface>
        </collision>
        <visual name="visual">
          <geometry>
            <plane><normal>0 0 1</normal><size>120 120</size></plane>
          </geometry>
          <material>
            <ambient>0.33 0.24 0.16 1</ambient>
            <diffuse>0.42 0.30 0.19 1</diffuse>
            <specular>0.02 0.02 0.02 1</specular>
          </material>
        </visual>
      </link>
    </model>
'''


def soil_bed(row_index, y, length, width=0.55):
    """A slightly raised soil ridge under each row - visual only."""
    return f'''
    <model name="bed_{row_index}">
      <static>true</static>
      <pose>{length/2 - 0.5:.3f} {y:.3f} 0.03 0 0 0</pose>
      <link name="link">
        <visual name="visual">
          <geometry><box><size>{length:.2f} {width} 0.06</size></box></geometry>
          <material>
            <ambient>0.22 0.15 0.10 1</ambient>
            <diffuse>0.28 0.19 0.12 1</diffuse>
          </material>
        </visual>
        <collision name="collision">
          <geometry><box><size>{length:.2f} {width} 0.06</size></box></geometry>
        </collision>
      </link>
    </model>
'''


def plant_model(name, x, y, yaw, fruit_names):
    """One tomato plant: stem + foliage, anchored to the world."""
    detachables = ""
    for i, fruit in enumerate(fruit_names):
        detachables += f'''
      <plugin filename="gz-sim-detachable-joint-system"
              name="gz::sim::systems::DetachableJoint">
        <parent_link>stem</parent_link>
        <child_model>{fruit}</child_model>
        <child_link>fruit</child_link>
        <detach_topic>/{fruit}/detach</detach_topic>
      </plugin>'''

    return f'''
    <model name="{name}">
      <pose>{x:.3f} {y:.3f} 0 0 0 {yaw:.3f}</pose>

      <!-- anchor to the world: keeps the plant upright but leaves it a
           dynamic model, which DetachableJoint requires -->
      <joint name="anchor" type="fixed">
        <parent>world</parent>
        <child>stem</child>
      </joint>

      <link name="stem">
        <pose>0 0 {STEM_HEIGHT/2:.3f} 0 0 0</pose>
        <inertial>
          <mass>1.5</mass>
          <inertia><ixx>0.1</ixx><iyy>0.1</iyy><izz>0.01</izz>
                   <ixy>0</ixy><ixz>0</ixz><iyz>0</iyz></inertia>
        </inertial>
        <collision name="collision">
          <geometry>
            <cylinder><radius>{STEM_RADIUS}</radius><length>{STEM_HEIGHT}</length></cylinder>
          </geometry>
        </collision>
        <visual name="visual">
          <geometry>
            <cylinder><radius>{STEM_RADIUS}</radius><length>{STEM_HEIGHT}</length></cylinder>
          </geometry>
          <material>
            <ambient>0.18 0.30 0.12 1</ambient>
            <diffuse>0.24 0.42 0.16 1</diffuse>
          </material>
        </visual>

        <!-- foliage: visual only, so the arm can reach through leaves.
             Give it a collision later if you want a harder challenge. -->
        <visual name="foliage">
          <pose>0 0 {FOLIAGE_Z - STEM_HEIGHT/2:.3f} 0 0 0</pose>
          <geometry><sphere><radius>{FOLIAGE_RADIUS}</radius></sphere></geometry>
          <material>
            <ambient>0.15 0.33 0.11 1</ambient>
            <diffuse>0.22 0.48 0.15 1</diffuse>
            <specular>0.05 0.08 0.05 1</specular>
          </material>
          <transparency>0.15</transparency>
        </visual>
      </link>
{detachables}
    </model>
'''


def fruit_model(name, x, y, z, ripe=True):
    """A single tomato: its own dynamic model so it can be detached and carried."""
    if ripe:
        ambient, diffuse = "0.45 0.05 0.03 1", "0.80 0.10 0.06 1"
    else:
        ambient, diffuse = "0.30 0.35 0.10 1", "0.55 0.62 0.18 1"

    inertia = 2.0 / 5.0 * FRUIT_MASS * FRUIT_RADIUS ** 2

    return f'''
    <model name="{name}">
      <pose>{x:.3f} {y:.3f} {z:.3f} 0 0 0</pose>
      <link name="fruit">
        <inertial>
          <mass>{FRUIT_MASS}</mass>
          <inertia><ixx>{inertia:.6f}</ixx><iyy>{inertia:.6f}</iyy><izz>{inertia:.6f}</izz>
                   <ixy>0</ixy><ixz>0</ixz><iyz>0</iyz></inertia>
        </inertial>
        <collision name="collision">
          <geometry><sphere><radius>{FRUIT_RADIUS}</radius></sphere></geometry>
          <surface>
            <friction><ode><mu>1.5</mu><mu2>1.5</mu2></ode></friction>
            <contact><ode><min_depth>0.002</min_depth><kp>100000</kp></ode></contact>
          </surface>
        </collision>
        <visual name="visual">
          <geometry><sphere><radius>{FRUIT_RADIUS}</radius></sphere></geometry>
          <material>
            <ambient>{ambient}</ambient>
            <diffuse>{diffuse}</diffuse>
            <specular>0.3 0.3 0.3 1</specular>
          </material>
        </visual>
      </link>
    </model>
'''


def main():
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--output', default='tomato_field.sdf')
    p.add_argument('--world-name', default='tomato_field')
    p.add_argument('--rows', type=int, default=3)
    p.add_argument('--plants-per-row', type=int, default=6)
    p.add_argument('--row-spacing', type=float, default=1.8,
                   help='distance between rows (m)')
    p.add_argument('--plant-spacing', type=float, default=0.65,
                   help='distance between plants within a row (m)')
    p.add_argument('--fruits', type=int, default=2,
                   help='fruits per plant')
    p.add_argument('--unripe-ratio', type=float, default=0.3,
                   help='fraction of fruit that is green (0-1)')
    p.add_argument('--start-x', type=float, default=2.0,
                   help='distance from the origin to the first plant (m)')
    p.add_argument('--seed', type=int, default=42)
    args = p.parse_args()

    random.seed(args.seed)

    sdf = [header(args.world_name)]
    row_length = args.plants_per_row * args.plant_spacing

    n_plants = 0
    n_fruits = 0

    for r in range(args.rows):
        # rows are centred on y = 0
        y_row = (r - (args.rows - 1) / 2.0) * args.row_spacing

        sdf.append(soil_bed(r, y_row, row_length + 0.6))

        for c in range(args.plants_per_row):
            x = args.start_x + c * args.plant_spacing
            # a little jitter so the field does not look like a spreadsheet
            jx = x + random.uniform(-0.04, 0.04)
            jy = y_row + random.uniform(-0.05, 0.05)
            yaw = random.uniform(0, 2 * math.pi)

            plant_name = f'plant_{r}_{c}'
            fruit_names = []
            fruit_blocks = []

            for f in range(args.fruits):
                fruit_name = f'tomato_{r}_{c}_{f}'
                # hang the fruit off to the side of the stem, alternating sides
                angle = random.uniform(0, 2 * math.pi)
                offset = FRUIT_RADIUS + STEM_RADIUS + 0.06
                fx = jx + offset * math.cos(angle)
                fy = jy + offset * math.sin(angle)
                fz = FRUIT_HEIGHTS[f % len(FRUIT_HEIGHTS)]
                ripe = random.random() > args.unripe_ratio

                fruit_names.append(fruit_name)
                fruit_blocks.append(fruit_model(fruit_name, fx, fy, fz, ripe))
                n_fruits += 1

            sdf.append(plant_model(plant_name, jx, jy, yaw, fruit_names))
            sdf.extend(fruit_blocks)
            n_plants += 1

    sdf.append('\n  </world>\n</sdf>\n')

    with open(args.output, 'w') as fh:
        fh.write(''.join(sdf))

    print(f'wrote {args.output}')
    print(f'  {args.rows} rows x {args.plants_per_row} plants = {n_plants} plants')
    print(f'  {n_fruits} fruits')
    print(f'  field extends roughly x=[{args.start_x:.1f}, '
          f'{args.start_x + row_length:.1f}], '
          f'y=[{-(args.rows-1)/2*args.row_spacing:.1f}, '
          f'{(args.rows-1)/2*args.row_spacing:.1f}]')
    print()
    print('detach a fruit from the command line with:')
    print('  gz topic -t /tomato_0_0_0/detach -m gz.msgs.Empty -p ""')


if __name__ == '__main__':
    main()
